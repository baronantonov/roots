import os
import re

ROOT_DIR = "/home/antigravity/baronantonov/roots"

def load_claims():
    path = os.path.join(ROOT_DIR, "claims-register.csv")
    with open(path, "r", encoding="utf-8") as f:
        return list(csv.DictReader(f))

def load_artifacts():
    path = os.path.join(ROOT_DIR, "artifact-register.csv")
    with open(path, "r", encoding="utf-8") as f:
        return list(csv.DictReader(f))

def sync_final_report():
    report_path = os.path.join(ROOT_DIR, "final-report.md")
    with open(report_path, "r", encoding="utf-8") as f:
        text = f.read()

    claims = load_claims()
    artifacts = load_artifacts()

    # 1. Формируем таблицу утверждений (Раздел 8)
    table_lines = [
        "| Claim ID | Утверждение | Статус | Поддержка | Противоречия | Обоснование |",
        "|---|---|---|---|---|---|"
    ]
    for c in claims:
        cid = c["claim_id"]
        ctext = c["claim_text"].replace("\n", " ").replace("|", "/")
        status = c["status"]
        arts = c["artifact_ids"].replace(";", "; ")
        arts_fmt = f"`[{arts}]`" if arts else "нет"
        contra = c["contradicting_artifact_ids"] if c.get("contradicting_artifact_ids") else "нет"
        rationale = c["rationale"].replace("\n", " ").replace("|", "/")
        table_lines.append(f"| `{cid}` | {ctext} | `{status}` | {arts_fmt} | {contra} | {rationale} |")
    new_claims_table = "\n".join(table_lines)

    claims_pattern = r"(\| Claim ID \| Утверждение \|.*?\n)(?=\n---\n\n## 9\. Существенные противоречия)"
    if re.search(claims_pattern, text, re.DOTALL):
        text = re.sub(claims_pattern, new_claims_table + "\n", text, flags=re.DOTALL)
        print(f"Updated claims table in final-report.md ({len(claims)} claims)")
    else:
        print("WARNING: claims table pattern not found in final-report.md")

    # 2. Формируем таблицу артефактов (Раздел 12)
    art_table_lines = [
        "| Artifact ID | Источник | Тип | Архивная ссылка/URL | Independence group | Оценка |",
        "|---|---|---|---|---|---|"
    ]
    for a in artifacts:
        aid = a["artifact_id"]
        title = a["source_title"].replace("|", "/").replace("\n", " ")
        stype = a["source_type"]
        ref = (a["archival_reference"] if a["archival_reference"] else a["source_url_or_path"]).replace("|", "/").replace("\n", " ")
        ig = a["independence_group"]
        notes = (a.get("reliability_notes") or a.get("summary") or "").replace("|", "/").replace("\n", " ")
        art_table_lines.append(f"| `{aid}` | {title} | `{stype}` | {ref} | `{ig}` | {notes} |")
    new_art_table = "\n".join(art_table_lines)

    art_pattern = r"(\| Artifact ID \| Источник \|.*?\n)(?=\n---\n\n## 13\. Ограничения и приватность)"
    if re.search(art_pattern, text, re.DOTALL):
        text = re.sub(art_pattern, new_art_table + "\n", text, flags=re.DOTALL)
        print(f"Updated artifacts table in final-report.md ({len(artifacts)} artifacts)")
    else:
        print("WARNING: artifacts table pattern not found in final-report.md")

