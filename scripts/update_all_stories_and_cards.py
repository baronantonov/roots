def update_html_content(content):
    p_start = content.find("const PERSONS = [")
    if p_start == -1:
        raise ValueError("const PERSONS not found in HTML")
    p_end = content.find("];\n\nconst ARTIFACTS", p_start)
    if p_end == -1:
        p_end = content.find("];", p_start)
    if p_end == -1:
        raise ValueError("End of const PERSONS not found in HTML")

    s = content[p_start:p_end+2]
    
    # Track person object positions
    # We will do replacement backwards from end to start so indices stay valid
    all_pids = [f"P-{i:04d}" for i in range(1, 43)]
    objects = []
    
    for pid in all_pids:
        idx = s.find(f'id: "{pid}"')
        if idx == -1:
            raise ValueError(f"Person {pid} not found in PERSONS array")
        open_brace = s.rfind("{", 0, idx)
        depth = 0
        in_str = False
        qc = ""
        close_brace = -1
        for i in range(open_brace, len(s)):
            c = s[i]
            if in_str:
                if c == "\\" and i + 1 < len(s):
                    pass
                elif c == qc:
                    in_str = False
            else:
                if c in ('"', "'"):
                    in_str = True
                    qc = c
                elif c == "{":
                    depth += 1
                elif c == "}":
                    depth -= 1
                    if depth == 0:
                        close_brace = i
                        break
        if close_brace == -1:
            raise ValueError(f"Matching brace not found for {pid}")
        objects.append((pid, open_brace, close_brace + 1, s[open_brace:close_brace+1]))

    # Sort objects by open_brace descending so we can replace in string safely
    objects.sort(key=lambda x: x[1], reverse=True)
    
    s_new = s
    for pid, start_idx, end_idx, obj_str in objects:
        data = PERSONS_DATA[pid]
        new_obj = obj_str
        
        # 1. Update or insert rationale
        rat_json = json.dumps(data["rationale"], ensure_ascii=False)
        if "rationale:" in new_obj:
            new_obj = re.sub(r'rationale:\s*"(?:\\.|[^"\\])*"', lambda m: f'rationale: {rat_json}', new_obj)
        else:
            new_obj = re.sub(r'(\n\s*story:)', lambda m: f'\n    rationale: {rat_json},{m.group(1)}', new_obj)
            
        # 2. Update story
        story_json = json.dumps(data["story"], ensure_ascii=False)
        new_obj = re.sub(r'story:\s*"(?:\\.|[^"\\])*"', lambda m: f'story: {story_json}', new_obj)
        
        # 3. Update occupation
        if "occupation" in data:
            occ_json = json.dumps(data["occupation"], ensure_ascii=False)
            if "occupation:" in new_obj:
                new_obj = re.sub(r'occupation:\s*"(?:\\.|[^"\\])*"', lambda m: f'occupation: {occ_json}', new_obj)
            else:
                new_obj = re.sub(r'(\n\s*relatives:)', lambda m: f'\n    occupation: {occ_json},{m.group(1)}', new_obj)
                
        # Replace in s_new
        s_new = s_new[:start_idx] + new_obj + s_new[end_idx:]

    content_new = content[:p_start] + s_new + content[p_end+2:]
    return content_new


def update_html_files():
    for fn in ["dashboard.html", "index.html"]:
        path = os.path.join(BASE_DIR, fn)
        print(f"Updating {path}...")
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()
        updated = update_html_content(content)
        with open(path, "w", encoding="utf-8") as f:
            f.write(updated)
        print(f"Successfully updated {fn} ({len(updated)} bytes).")


